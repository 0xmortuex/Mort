#!/usr/bin/env python3
"""Generate selfhost/cg_helper_text.mx from mort/codegen.py's helper text.

Usage: python selfhost/tools/gen_helper_text.py

The concurrency, network and random helpers are constant C text that
CodeGen writes one `_emit` at a time. Generating the Mort functions from what
those methods really emit keeps roughly 900 lines of escaped C out of hand
editing; the differential test compares the output with Python's either way.
"""
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUTPUT = HERE.parent / "cg_helper_text.mx"
sys.path.insert(0, str(ROOT))

from mort.codegen import CodeGen  # noqa: E402

FLAGS = ("used_threads", "used_mutexes", "used_atomics", "used_network",
         "used_secure_random")


def emitted(method, **on):
    generator = CodeGen.__new__(CodeGen)
    generator.lines = []
    generator.indent = 0
    generator.freestanding = False
    for flag in FLAGS:
        setattr(generator, flag, on.get(flag, False))
    method(generator)
    return generator.lines


def literal(text):
    out = []
    for char in text:
        if char in '\\"':
            out.append("\\" + char)
        elif " " <= char <= "~":
            out.append(char)
        else:
            raise ValueError(f"unexpected character {char!r} in helper text")
    return '"' + "".join(out) + '"'


def function(name, lines):
    body = "".join(f"    cg_em(g, {literal(line)});\n" for line in lines)
    return f"fn {name}(g: *Cg) {{\n{body}}}\n"


def split_concurrency():
    method = CodeGen._gen_concurrency_helpers
    threads = emitted(method, used_threads=True)
    mutexes = emitted(method, used_mutexes=True)
    atomics = emitted(method, used_atomics=True)
    prefix = 0
    while threads[prefix] == mutexes[prefix] == atomics[prefix]:
        prefix += 1
    # The closing `#undef` and its blank line; each section ends in its own blank.
    suffix = 2
    assert threads[-suffix:] == mutexes[-suffix:] == atomics[-suffix:]
    parts = {
        "prefix": threads[:prefix],
        "threads": threads[prefix:-suffix],
        "mutexes": mutexes[prefix:-suffix],
        "atomics": atomics[prefix:-suffix],
        "suffix": threads[-suffix:],
    }
    combined = emitted(
        method, used_threads=True, used_mutexes=True, used_atomics=True)
    assert combined == (parts["prefix"] + parts["threads"] + parts["mutexes"]
                        + parts["atomics"] + parts["suffix"])
    return parts


def main():
    parts = split_concurrency()
    sections = [
        "// Generated by selfhost/tools/gen_helper_text.py from mort/codegen.py.\n"
        "// Do not edit by hand.\n\nimport codegen;\n",
    ]
    for key in ("prefix", "threads", "mutexes", "atomics", "suffix"):
        sections.append(function(f"cgt_concurrency_{key}", parts[key]))
    sections.append(function(
        "cgt_network", emitted(CodeGen._gen_network_helpers, used_network=True)))
    sections.append(function(
        "cgt_secure_random",
        emitted(CodeGen._gen_secure_random_helpers, used_secure_random=True)))
    OUTPUT.write_bytes("\n".join(sections).encode("ascii"))
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
