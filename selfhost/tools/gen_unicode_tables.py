#!/usr/bin/env python3
"""Generate selfhost/lexer_unicode.mx from this Python's str classification.

Usage: python selfhost/tools/gen_unicode_tables.py

The Python lexer uses str.isalpha/isalnum for identifiers and repr() in one
diagnostic, so the Mort lexer needs the same three predicates. Only code points
at or above 0x80 are tabulated; ASCII is decided in lexer.mx.
"""
import platform
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "lexer_unicode.mx"
FIRST = 0x80
LAST = 0x10FFFF


def ranges(predicate):
    found = []
    start = None
    for code in range(FIRST, LAST + 2):
        member = code <= LAST and predicate(chr(code))
        if member and start is None:
            start = code
        elif not member and start is not None:
            found.append((start, code - 1))
            start = None
    return found


def table(name, items):
    values = []
    for start, end in items:
        values.append(str(start))
        values.append(str(end))
    lines = []
    for index in range(0, len(values), 12):
        lines.append("    " + ", ".join(values[index:index + 12]) + ",")
    lines[-1] = lines[-1].rstrip(",")
    return (f"const {name}_COUNT: u64 = {len(items)};\n"
            f"let {name}: [u32; {len(values)}] = [\n" + "\n".join(lines) + "\n];\n")


def main():
    parts = [
        "// GENERATED by selfhost/tools/gen_unicode_tables.py. Do not edit.\n"
        f"// Python {platform.python_version()}, Unicode {unicodedata.unidata_version}.\n"
        "// Each table is sorted inclusive pairs: start, end.\n\n",
        table("UNI_ALPHA", ranges(str.isalpha)), "\n",
        table("UNI_ALNUM", ranges(str.isalnum)), "\n",
        table("UNI_NONPRINT", ranges(lambda c: not c.isprintable())),
    ]
    OUTPUT.write_text("".join(parts), encoding="ascii", newline="\n")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
