#!/usr/bin/env python3
"""Reference declaration dump: the real Python checker, instrumented for T4.

The Mort checker (T4) implements the declaration phase and name resolution of
``mort/typechecker.py``, and leaves everything that needs an expression's type
to T5. This file drives the unmodified compiler (``compile_files_to_c``) with
``Checker`` replaced by an instrumented subclass and code generation stopped.

Output, shared with ``check_main.mx`` (ASCII, LF only). "q" values are the
quoted form from ``py_ast_dump.py``:

    alias q(name) q(target)
    enum-template q(name) params
    enum q(name)
    variant q(enum) q(name) q(payload_type)|- payloads
    struct-template q(name) params
    struct q(name)
    field q(struct) q(name) q(type)
    fn-template q(symbol) params q(ret) ptypes module public
    fn q(symbol) ptypes q(ret) module public kind
    resource-struct q(name)
    destructor-template q(name) q(symbol)
    destructor q(symbol)
    extern q(name)
    global q(name) q(decl_type)|- mutable
    --events--
    fn q(symbol)                 a function body begins
    bind q(name) q(kind) dN LM   a binding is declared (scope depth, decl line)
    var q(name) WHERE            a variable reference; WHERE is one of
                                 local dN LM, global, fn q(symbol)
    move q(name) local dN LM
    call q(name) enum | builtin | local dN LM | global | fn q(symbol)
    field q(obj) q(field) enum | fn q(symbol)
    struct q(name)               a struct literal finished

The tables are taken at the end of the declaration phase, before any function
body runs: they are what T4 owns. Events are in evaluation order. A function
body generated by a generic instantiation produces no events.

Comparing the two implementations (see the test): tables and diagnostics must
be equal when Python's first error is one T4 implements or when there is no
error. When Python's first error needs an expression's type (T5), the Mort
checker is expected to continue past it, so its events only need to extend the
Python events.

Hash order: the checker's ``set`` iteration decides which of several aggregate
cycles gets named. ``_OrderedSet`` makes that insertion ordered for this
reference only (see ``selfhost/PLAN.md``, section 11).
"""
