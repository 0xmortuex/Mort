class _OrderedSet:
    """The parts of `set` the checker uses, iterating in insertion order."""

    def __init__(self, items=()):
        self._items = {}
        self.update(items)

    def add(self, item):
        self._items[item] = True

    def update(self, items):
        for item in items:
            self._items[item] = True

    def union(self, *others):
        merged = _OrderedSet(self)
        for other in others:
            merged.update(other)
        return merged

    def __iter__(self):
        return iter(self._items)

    def __contains__(self, item):
        return item in self._items

    def __len__(self):
        return len(self._items)

    def __sub__(self, other):
        return _OrderedSet(item for item in self if item not in other)

    def __bool__(self):
        return bool(self._items)


def names_text(names):
    return "[" + ",".join(q(name) for name in names) + "]"


class _StopCodegen(Exception):
    pass


class _DumpChecker(Checker):
    """The real checker with logging around name resolution."""

    def __init__(self, program, freestanding=False, test_mode=False):
        self._scopes = None
        self._binding_scopes = None
        self.tables = None
        self.events = []
        self.suppressed = False
        self.frozen = False
        self.needs_type = False
        self._match_stack = []
        super().__init__(program, freestanding=freestanding, test_mode=test_mode)
        LAST[0] = self

    # ----- logging helpers -----
    @property
    def scopes(self):
        return self._scopes

    @scopes.setter
    def scopes(self, value):
        self._scopes = value

    @property
    def binding_scopes(self):
        return self._binding_scopes

    @binding_scopes.setter
    def binding_scopes(self, value):
        self._binding_scopes = _LoggedBindings(value, self)

    def _emit(self, text):
        if not self.suppressed and not self.frozen:
            self.events.append(text)

    def _where(self, name):
        for depth in range(len(self.scopes), 0, -1):
            if name in self.scopes[depth - 1]:
                binding = self.binding_scopes[depth - 1].get(name)
                return f"local d{depth} L{getattr(binding['node'], 'line', 0)}"
        if name in self.globals:
            return "global"
        return None

    def _snapshot(self):
        if self.tables is not None:
            return
        out = []
        for name, target in self.aliases.items():
            out.append(f"alias {q(name)} {q(target)}\n")
        for name, decl in self.enum_templates.items():
            out.append(f"enum-template {q(name)} {names_text(decl.generic_params)}\n")
        for name, variants in self.enums.items():
            out.append(f"enum {q(name)}\n")
            for variant, payload in variants.items():
                text = q(payload) if payload is not None else "-"
                payloads = names_text(self.enum_payloads[name][variant])
                out.append(f"variant {q(name)} {q(variant)} {text} {payloads}\n")
        for name, decl in self.struct_templates.items():
            out.append(f"struct-template {q(name)} {names_text(decl.generic_params)}\n")
        for name, fields in self.structs.items():
            out.append(f"struct {q(name)}\n")
            for field, typ in fields.items():
                out.append(f"field {q(name)} {q(field)} {q(typ)}\n")
        for symbol, decl in self.func_templates.items():
            ptypes = names_text(parameter.typ for parameter in decl.params)
            out.append(
                f"fn-template {q(symbol)} {names_text(decl.generic_params)} "
                f"{q(decl.ret)} {ptypes} {self._fn_attrs(decl)}\n")
        for symbol, (ptypes, ret) in self.funcs.items():
            decl = self.func_decls[symbol]
            kind = "extern" if isinstance(decl, A.ExternFnDecl) else "fn"
            out.append(
                f"fn {q(symbol)} {names_text(ptypes)} {q(ret)} "
                f"{self._fn_attrs(decl)} {kind}\n")
        for name in self.resource_struct_names:
            out.append(f"resource-struct {q(name)}\n")
        for name, symbol in self.resource_destructor_templates.items():
            out.append(f"destructor-template {q(name)} {q(symbol)}\n")
        for symbol in self.destructor_symbols:
            out.append(f"destructor {q(symbol)}\n")
        for name in self.extern_names:
            out.append(f"extern {q(name)}\n")
        for declaration in self.program.globals:
            if declaration.name in self.globals:
                decl_type = q(declaration.decl_type) if declaration.decl_type else "-"
                mutable = 1 if self.global_mutable[declaration.name] else 0
                out.append(f"global {q(declaration.name)} {decl_type} {mutable}\n")
        self.tables = "".join(out)

    @staticmethod
    def _fn_attrs(decl):
        module = getattr(decl, "module", None)
        module_text = q(module) if module else "-"
        public = 1 if getattr(decl, "public", False) else 0
        return f"{module_text} {public}"

    # ----- hooks -----
    def _check_fn(self, f):
        self._snapshot()
        self.suppressed = "<" in f.symbol_name
        if not self.suppressed:
            self._emit(f"fn {q(f.symbol_name)}\n")
        try:
            super()._check_fn(f)
        finally:
            self.suppressed = False

    def _check_stmt(self, s):
        self._snapshot()
        if isinstance(s, A.Match):
            self._match_stack.append(s)
            try:
                super()._check_stmt(s)
            finally:
                self._match_stack.pop()
        else:
            super()._check_stmt(s)

    def _contains_try(self, expression):
        if (self._match_stack and isinstance(expression, A.Call)
                and any(arm.pattern is expression
                        for arm in self._match_stack[-1].arms)):
            self._note_pattern(self._match_stack[-1], expression)
        return Checker._contains_try(expression)

    def _note_pattern(self, match, pattern):
        """Payload patterns are chosen by the subject type, which T4 doesn't
        have: it decides from the qualified name. Past a disagreement (always
        a type error in a correct program) the two walks are not comparable."""
        name = pattern.name
        if "." not in name:
            return
        subject_type = match.expr.type
        prefix = name.rsplit(".", 1)[0]
        python_payload = (
            subject_type in self.enums and name.startswith(subject_type + "."))
        generic = generic_parts(prefix)
        mort_payload = prefix in self.enums or (
            generic is not None and generic[0] in self.enum_templates)
        if python_payload != mort_payload or (
                python_payload and prefix != subject_type):
            self.needs_type = True
            self.frozen = True

    def _declare(self, name, typ, node, kind="variable", mutable=True):
        super()._declare(name, typ, node, kind=kind, mutable=mutable)
        self._emit(
            f"bind {q(name)} {q(kind)} d{len(self.scopes)} "
            f"L{getattr(node, 'line', 0)}\n")

    def _infer(self, e):
        if isinstance(e, A.Var):
            where = self._where(e.name)
            result = super()._infer(e)
            if where is None:
                where = f"fn {q(e.resolved_function)}"
            self._emit(f"var {q(e.name)} {where}\n")
            return result
        if isinstance(e, A.Move):
            result = super()._infer(e)
            self._emit(f"move {q(e.expr.name)} {self._where(e.expr.name)}\n")
            return result
        if isinstance(e, A.StructLit):
            result = super()._infer(e)
            self._emit(f"struct {q(e.name)}\n")
            return result
        if isinstance(e, A.FieldAccess):
            try:
                result = super()._infer(e)
            except MortError as error:
                if error.msg.startswith("struct "):
                    self.needs_type = True  # from field access on a value
                raise
            if e.resolved_function is not None:
                target = f"fn {q(e.resolved_function)}"
                self._emit(f"field {q(e.obj.name)} {q(e.field)} {target}\n")
            elif isinstance(e.obj, A.Var) and e.obj.name in self.enums:
                self._emit(f"field {q(e.obj.name)} {q(e.field)} enum\n")
            return result
        return super()._infer(e)

    def _infer_call(self, e):
        where = self._where(e.name) if "." not in e.name else None
        result = super()._infer_call(e)
        if e.enum_name is not None:
            target = "enum"
        elif e.name in BUILTIN_NAMES:
            target = "builtin"
        elif e.indirect:
            target = where
        else:
            target = f"fn {q(e.resolved_name.split('<', 1)[0])}"
        self._emit(f"call {q(e.name)} {target}\n")
        return result


class _LoggedBindings(list):
    """A scope stack that logs the bindings a scope is pushed with."""

    def __init__(self, items, owner):
        super().__init__(items)
        self.owner = owner

    def append(self, scope):
        super().append(scope)
        for name, binding in scope.items():
            self.owner._emit(
                f"bind {q(name)} {q(binding['kind'])} d{len(self.owner.scopes)} "
                f"L{getattr(binding['node'], 'line', 0)}\n")


LAST = [None]


class Result(types.SimpleNamespace):
    """One run of the reference.

    tables   text, or None if the declaration phase did not finish
    events   text
    error    MortError.format() text, or None
    t4       whether the error is one T4 implements
    manifest text for check_main (None: a parse or load error stopped the run)
    outcome  'ok', 'error', 'parse' (lexical or syntax error), 'load' (import
             resolution error, owned by T8) or 'crash'
    """


def message_is_t4(message):
    return any(pattern.fullmatch(message) for pattern in T4_MESSAGES)


def manifest_text(mode, programs):
    lines = [f"MODE {mode}\n"]
    for program in programs:
        lines.append(f"FILE {program.filename}\n")
        for alias, module in program.import_aliases.items():
            lines.append(f"ALIAS {alias} {module}\n")
    return "".join(lines)


def run_reference(path, mode, recursion_limit=1_000_000):
    """Run the compiler's own pipeline over one root file."""
    captured = []
    original_compile = mortc._compile_programs
    original_checker, original_codegen = mortc.Checker, mortc.CodeGen
    original_set = getattr(typechecker, "set", None)
    limit = sys.getrecursionlimit()

    def capture(programs, *args, **kwargs):
        captured.append(programs)
        return original_compile(programs, *args, **kwargs)

    def stop_codegen(*args, **kwargs):
        raise _StopCodegen

    LAST[0] = None
    mortc._compile_programs = capture
    mortc.Checker, mortc.CodeGen = _DumpChecker, stop_codegen
    typechecker.set = _OrderedSet
    sys.setrecursionlimit(recursion_limit)
    try:
        error = None
        try:
            mortc.compile_files_to_c(
                [str(path)], freestanding=mode == "freestanding",
                test_mode=mode == "test")
        except _StopCodegen:
            pass
        except MortError as raised:
            error = raised
    finally:
        sys.setrecursionlimit(limit)
        mortc._compile_programs = original_compile
        mortc.Checker, mortc.CodeGen = original_checker, original_codegen
        if original_set is None:
            del typechecker.set
        else:
            typechecker.set = original_set

    checker = LAST[0]
    if checker is None:
        loader = error is not None and LOADER_MESSAGE.fullmatch(error.msg)
        outcome = "load" if loader or error is None else "parse"
        return Result(tables=None, events="", error=error.format() if error else None,
                      t4=False, manifest=None, outcome=outcome,
                      failing_file=getattr(error, "filename", None))
    if error is None:
        checker._snapshot()
    elif error.msg in ("no 'main' function defined", "'main' must take no parameters",
                       "'main' must return int"):
        checker._snapshot()
    events = "".join(checker.events)
    return Result(
        tables=checker.tables,
        events=events,
        error=error.format() if error is not None else None,
        t4=error is not None and not checker.needs_type and message_is_t4(error.msg),
        manifest=manifest_text(mode, captured[0]),
        outcome="ok" if error is None else "error",
        failing_file=None,
    )


def main(argv):
    if len(argv) != 3 or argv[2] not in ("hosted", "test", "freestanding"):
        print("usage: py_check_dump.py FILE hosted|test|freestanding", file=sys.stderr)
        return 2
    result = run_reference(Path(argv[1]).resolve(), argv[2])
    if result.tables:
        sys.stdout.write(result.tables)
    sys.stdout.write(EVENTS_MARK)
    sys.stdout.write(result.events)
    if result.error:
        print(result.error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
